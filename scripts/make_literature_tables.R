#!/usr/bin/env Rscript
# =============================================================================
# make_literature_tables.R -- render Online Resource 1, Tables S1 and S2 from
# the deposited literature search files:
#   data/literature/search_strategy.csv        -> manuscript/supp_search_table.tex  (Table S1)
#   data/literature/response_term_mapping.csv  -> manuscript/supp_regex_table.tex   (Table S2)
#
# Both CSVs are the author's own material, transcribed from the original
# supplementary document; record counts in search_strategy.csv are those
# reported in the Methods of the earlier submission. This script only typesets.
# =============================================================================
suppressPackageStartupMessages(library(utils))

root <- normalizePath(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), ".."))
ddir <- file.path(root, "data", "literature")
mdir <- file.path(root, "manuscript")

# Escape for ordinary text cells ------------------------------------------------
tex_text <- function(x) {
  x <- gsub("\\\\", "\\\\textbackslash{}", x)
  x <- gsub("([&%$#_{}])", "\\\\\\1", x)
  x <- gsub("/", "/\\\\allowbreak{}", x)   # let long family and sub metric labels break after a slash
  gsub("-", "-\\\\allowbreak{}", x)        # and after a hyphen inside a compound label
}
# Escape for the regex column, set in \texttt{} with allowed line breaks after '|'
tex_code <- function(x) {
  x <- gsub("\\\\", "\\\\textbackslash{}", x)
  x <- gsub("([&%$#_{}])", "\\\\\\1", x)
  x <- gsub("\\^", "\\\\^{}", x)
  x <- gsub("~", "\\\\~{}", x)
  # Patterns are reproduced verbatim (spaces included); only break opportunities are added
  x <- gsub("\\|", "|\\\\allowbreak{}", x)
  x <- gsub("\\(", "\\\\allowbreak{}(", x)
  paste0("\\texttt{", x, "}")
}

# =============================================================================
# Table S1: search strategy
# =============================================================================
ss <- read.csv(file.path(ddir, "search_strategy.csv"), stringsAsFactors = FALSE, encoding = "UTF-8")
stopifnot(all(c("database", "search_string", "records") %in% names(ss)))
tex_query <- function(x) {   # Boolean strings verbatim, straight double quotes, breakable after operators
  x <- gsub("([&%$#_{}])", "\\\\\\1", x)
  x <- gsub("\"", "\\\\textquotedbl{}", x)
  gsub("<", "\\\\textless{}", gsub(">", "\\\\textgreater{}", x))
}
s1 <- c(
  "% GENERATED by scripts/make_literature_tables.R from data/literature/search_strategy.csv -- do not edit",
  "\\begin{table}[H]\\centering",
  "\\caption{Search strings applied to each database, reproduced verbatim, with the number of records retrieved. The asterisk denotes truncation; TS, topic field (Web of Science); PY, publication year.}",
  "\\label{tab:search}\\footnotesize\\setlength{\\tabcolsep}{4pt}",
  "\\begin{tabular}{>{\\raggedright\\arraybackslash}p{2.1cm}>{\\raggedright\\arraybackslash}p{11.6cm}r}\\toprule",
  "Database & Search string & Records \\\\\\midrule",
  sprintf("%s & %s & %s \\\\", tex_text(ss$database), tex_query(ss$search_string), format(ss$records, big.mark = ",")),
  "\\midrule",
  sprintf("Total before de duplication & & %s \\\\", format(sum(ss$records), big.mark = ",")),
  "\\bottomrule\\end{tabular}\\end{table}")
writeLines(s1, file.path(mdir, "supp_search_table.tex"))
cat("wrote supp_search_table.tex with", nrow(ss), "databases\n")

# =============================================================================
# Table S2: response term mapping
# =============================================================================
m <- read.csv(file.path(ddir, "response_term_mapping.csv"), stringsAsFactors = FALSE, encoding = "UTF-8")
stopifnot(all(c("raw_terms", "regex", "submetric", "family") %in% names(m)))
out <- file.path(mdir, "supp_regex_table.tex")

# Rows and columns follow the author's table exactly: Raw terms | Matched regex |
# Submetric | Family, with the family named on the first row of its group only.
fam_order <- unique(m$family)
rows <- character(0)
for (f in fam_order) {
  g <- m[m$family == f, ]
  for (i in seq_len(nrow(g))) {
    fam_cell <- if (i == 1) tex_text(f) else ""
    rows <- c(rows, sprintf("%s & %s & %s & %s \\\\",
                            tex_text(g$raw_terms[i]), tex_code(g$regex[i]), tex_text(g$submetric[i]), fam_cell))
  }
  if (f != fam_order[length(fam_order)]) rows <- c(rows, "\\addlinespace")
}

hdr <- c(
  "% GENERATED by scripts/make_literature_tables.R from data/literature/response_term_mapping.csv -- do not edit",
  "\\begin{footnotesize}",
  "\\setlength{\\tabcolsep}{4pt}",
  "\\begin{longtable}{>{\\raggedright\\arraybackslash}p{5.4cm}>{\\raggedright\\arraybackslash}p{5.1cm}>{\\raggedright\\arraybackslash}p{2.2cm}>{\\raggedright\\arraybackslash}p{2.0cm}}",
  "\\caption{Regex patterns for mapping response terms to standardised submetrics and response families. Raw terms are those extracted from the studies' response fields; patterns were applied case insensitively.}\\label{tab:regex}\\\\",
  "\\toprule",
  "Raw terms & Matched regex & Submetric & Family \\\\",
  "\\midrule",
  "\\endfirsthead",
  "\\multicolumn{4}{l}{\\small Table~\\thetable{} (continued)}\\\\",
  "\\toprule",
  "Raw terms & Matched regex & Submetric & Family \\\\",
  "\\midrule",
  "\\endhead",
  "\\midrule \\multicolumn{4}{r}{\\small continued on next page}\\\\",
  "\\endfoot",
  "\\bottomrule",
  "\\endlastfoot"
)

writeLines(c(hdr, rows, "\\end{longtable}", "\\end{footnotesize}"), out)
cat("wrote", out, "with", nrow(m), "rules\n")
